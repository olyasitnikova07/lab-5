# Вторая хеш-функция для двойного хеширования: определяет шаг, с которым мы «прыгаем» по таблице при коллизии.
def h2(k, m):
    # Шаг от 1 до m-1 (никогда не 0, иначе мы бы стояли на месте); так как m простое, шаг взаимно прост с m,
    # а значит, последовательность проб обойдёт все ячейки таблицы.
    return 1 + k % (m - 1)


# Класс ChainTable — хеш-таблица, где коллизии решаются методом цепочек: в каждой ячейке лежит список элементов.
class ChainTable:
    # Конструктор: создаёт пустую таблицу размера m; h — хеш-функция (по умолчанию хорошая h_mul).
    def __init__(self, m, h=h_mul):
        # Запоминаем размер таблицы, хеш-функцию, число элементов (пока 0) и счётчик проб (пока 0).
        self.m, self.h, self.n, self.probes = m, h, 0, 0
        # Создаём m пустых списков — по одному на каждую ячейку таблицы (в них будут лежать пары «ключ, значение»).
        self.slots = [[] for _ in range(m)]

    # Операция вставки: кладёт пару (ключ, значение) в таблицу или обновляет значение, если ключ уже есть.
    def insert(self, key, value):
        # Считаем номер ячейки по хеш-функции и берём список (цепочку), который лежит в этой ячейке.
        chain = self.slots[self.h(key, self.m)]
        # Просматриваем цепочку: i — номер элемента в цепочке, (k, _) — ключ и значение (значение нам тут не нужно).
        for i, (k, _) in enumerate(chain):
            # Каждый просмотренный элемент цепочки считаем одной «пробой» (так измеряем трудоёмкость).
            self.probes += 1
            # Если ключ в цепочке совпал с вставляемым — такой ключ уже есть в таблице.
            if k == key:
                # Тогда просто заменяем пару на новую (обновляем значение).
                chain[i] = (key, value)
                # Вставка закончена, выходим из функции.
                return
        # Если цикл закончился и ключа не нашли — добавляем новую пару в конец цепочки.
        chain.append((key, value))
        # Число элементов в таблице увеличилось на единицу.
        self.n += 1

    # Операция поиска: возвращает значение по ключу или None, если ключа нет.
    def search(self, key):
        # Идём по цепочке нужной ячейки: k — ключ элемента, v — его значение.
        for k, v in self.slots[self.h(key, self.m)]:
            # Считаем просмотренный элемент как одну пробу.
            self.probes += 1
            # Если ключ совпал — мы нашли то, что искали.
            if k == key:
                # Возвращаем найденное значение.
                return v
        # Дошли до конца цепочки и не нашли ключ — возвращаем None («ничего»).
        return None

    # Операция удаления: убирает ключ из таблицы; возвращает True, если удалили, и False, если такого ключа не было.
    def delete(self, key):
        # Берём цепочку из той ячейки, где должен лежать ключ.
        chain = self.slots[self.h(key, self.m)]
        # Просматриваем цепочку, запоминая номер элемента i.
        for i, (k, _) in enumerate(chain):
            # Каждый просмотренный элемент — одна проба.
            self.probes += 1
            # Если нашли нужный ключ…
            if k == key:
                # …удаляем эту пару из цепочки по её номеру.
                del chain[i]
                # Элементов в таблице стало на один меньше.
                self.n -= 1
                # Сообщаем, что удаление выполнено.
                return True
        # Ключ в цепочке не нашёлся — удалять было нечего.
        return False


# Класс DoubleHashTable — хеш-таблица с открытой адресацией: все элементы лежат прямо в массиве,
# а при коллизии мы ищем другую ячейку по правилу двойного хеширования.
class DoubleHashTable:
    # Две специальные метки-«заглушки»: EMPTY — ячейка никогда не использовалась, DELETED — элемент из неё удалён.
    # object() создаёт уникальный объект, который нельзя спутать ни с одним ключом.
    EMPTY, DELETED = object(), object()

    # Конструктор: создаёт пустую таблицу размера m с первой хеш-функцией h.
    def __init__(self, m, h=h_mul):
        # Запоминаем размер, хеш-функцию, число элементов и счётчик проб.
        self.m, self.h, self.n, self.probes = m, h, 0, 0
        # Массив ключей: сначала все m ячеек помечены как «пусто».
        self.keys = [self.EMPTY] * m
        # Массив значений: параллельный массив, в нём лежат значения для тех же ячеек (пока None).
        self.vals = [None] * m

    # Вспомогательная функция-генератор: по очереди выдаёт номера ячеек, которые нужно проверить для данного ключа.
    # Формула двойного хеширования: i-я проба = (h1 + i * h2) mod m.
    def _seq(self, key):
        # pos — начальная позиция (по первой хеш-функции), step — шаг (по второй хеш-функции).
        pos, step = self.h(key, self.m), h2(key, self.m)
        # Пробуем не больше m раз — столько ячеек всего в таблице.
        for _ in range(self.m):
            # yield отдаёт текущую позицию наружу и «замораживает» функцию до следующего запроса.
            yield pos
            # Переходим к следующей позиции: прибавляем шаг и берём остаток от деления на m (чтобы не выйти за таблицу).
            pos = (pos + step) % self.m

    # Операция вставки в таблицу с открытой адресацией.
    def insert(self, key, value):
        # free — первая ячейка, куда можно записать элемент (пока не найдена).
        free = None
        # Идём по последовательности проб для этого ключа.
        for pos in self._seq(key):
            # Каждая проверенная ячейка — одна проба.
            self.probes += 1
            # k — ключ, который сейчас лежит в проверяемой ячейке.
            k = self.keys[pos]
            # Если там уже лежит наш ключ…
            if k == key:
                # …просто обновляем его значение.
                self.vals[pos] = value
                # Вставка закончена.
                return
            # Если ячейка помечена «удалено» и подходящего места мы ещё не запомнили…
            if k is self.DELETED and free is None:
                # …запоминаем её: сюда можно будет записать, если такого ключа дальше в цепочке проб нет.
                free = pos
            # Если встретили пустую ячейку — значит, ключа в таблице точно нет (иначе мы бы дошли до него раньше).
            if k is self.EMPTY:
                # Выбираем место для записи: сначала запомненную «удалённую» ячейку, а если её нет — эту пустую.
                free = pos if free is None else free
                # Дальше искать не нужно, выходим из цикла.
                break
        # Если место так и не нашлось — таблица полностью заполнена.
        if free is None:
            # Сообщаем об ошибке (исключение RuntimeError).
            raise RuntimeError("Таблица переполнена")
        # Записываем ключ и значение в найденную ячейку.
        self.keys[free], self.vals[free] = key, value
        # Число элементов выросло на единицу.
        self.n += 1

    # Операция поиска в таблице с открытой адресацией.
    def search(self, key):
        # Идём по тем же ячейкам, по которым шла бы вставка этого ключа.
        for pos in self._seq(key):
            # Считаем пробу.
            self.probes += 1
            # Смотрим, что лежит в ячейке.
            k = self.keys[pos]
            # Пустая ячейка обрывает поиск: если бы ключ был в таблице, он лежал бы до первой пустой ячейки.
            if k is self.EMPTY:
                # Ключа в таблице нет.
                return None
            # Если ключ совпал…
            if k == key:
                # …возвращаем значение из параллельного массива.
                return self.vals[pos]
        # Просмотрели всю таблицу и не нашли — ключа нет.
        return None

    # Операция удаления в таблице с открытой адресацией.
    def delete(self, key):
        # Идём по последовательности проб для ключа.
        for pos in self._seq(key):
            # Считаем пробу.
            self.probes += 1
            # Берём ключ из проверяемой ячейки.
            k = self.keys[pos]
            # Пустая ячейка — значит, такого ключа в таблице нет.
            if k is self.EMPTY:
                # Удалять нечего.
                return False
            # Если нашли нужный ключ…
            if k == key:
                # …ставим в ячейку метку «удалено» (tombstone), а не «пусто»: иначе поиск других ключей оборвётся
                # на этой ячейке раньше времени и не найдёт элементы, лежащие дальше по цепочке проб.
                self.keys[pos], self.vals[pos] = self.DELETED, None
                # Элементов стало на один меньше.
                self.n -= 1
                # Удаление выполнено.
                return True
        # Ключ не найден.
        return False


# Класс StdDict — тонкая обёртка над встроенным словарём dict, чтобы у него были те же методы insert и search,
# что и у наших таблиц; так его можно проверять той же функцией measure (дополнительное задание В5).
class StdDict(dict):
    # Счётчик проб у словаря не ведётся, поэтому он всегда равен нулю.
    probes = 0

    # Вставка в словарь.
    def insert(self, key, value):
        # Обычная запись в словарь по ключу.
        self[key] = value

    # Поиск в словаре.
    def search(self, key):
        # Метод get вернёт значение или None, если ключа нет.
        return self.get(key)


# Функция check проверяет, что вставка, поиск и удаление работают правильно (на небольшом примере).
def check(table, keys):
    # Вставляем в таблицу все ключи из списка.
    for k in keys:
        # В качестве значения кладём сам ключ — так проще проверять.
        table.insert(k, k)
    # Берём каждый второй ключ (с шагом 2, начиная с нулевого) и удаляем его.
    for k in keys[::2]:
        # assert проверяет условие: если оно ложно, программа остановится с ошибкой; удаление должно вернуть True.
        assert table.delete(k)
    # Удалённые ключи теперь не должны находиться (поиск должен вернуть None).
    assert all(table.search(k) is None for k in keys[::2])
    # Остальные ключи (с номерами 1, 3, 5, …) должны по-прежнему находиться, и значение должно равняться ключу.
    assert all(table.search(k) == k for k in keys[1::2])


# Функция measure измеряет время вставки и два вида поиска (успешный и неуспешный), а также среднее число проб.
def measure(table, keys, hits, misses):
    # Запоминаем момент времени перед началом вставки.
    t0 = time.perf_counter()
    # Вставляем все ключи по одному.
    for k in keys:
        # Одна вставка (значение равно ключу).
        table.insert(k, k)
    # Список результатов: первым элементом кладём общее время вставки в секундах (текущее время минус начальное).
    res = [time.perf_counter() - t0]
    # Теперь два набора запросов: hits — ключи, которые есть в таблице, misses — ключи, которых в ней нет.
    for qs in (hits, misses):
        # Обнуляем счётчик проб, чтобы считать пробы только для этого набора запросов.
        table.probes = 0
        # Запоминаем момент начала поиска.
        t0 = time.perf_counter()
        # Выполняем все запросы набора.
        for q in qs:
            # Один поиск (результат нам не нужен, важно время и число проб).
            table.search(q)
        # Добавляем в результат два числа: среднее время одного запроса и среднее число проб на запрос.
        res += [(time.perf_counter() - t0) / len(qs), table.probes / len(qs)]
    # Возвращаем список из пяти чисел: время вставки, время и пробы успешного поиска, время и пробы неуспешного.
    return res


# Функция draw_graphs строит два графика и сохраняет их в файл lab5_graphs.png.
# alphas — значения коэффициента заполнения, exp — экспериментальные числа проб, lens — распределение длин цепочек.
def draw_graphs(alphas, exp, lens):
    # Создаём окно с двумя графиками рядом: левый — ax1, правый — ax2.
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))
    # Рисуем три экспериментальные линии: по оси X — alpha, по оси Y — среднее число проб.
    for name, ys in exp.items():
        # "o-" означает: точки соединены линией; label — подпись в легенде.
        ax1.plot(alphas, ys, "o-", label=name)
    # Сетка значений alpha от 0,05 до 0,96 для гладкой теоретической кривой.
    xs = [i / 100 for i in range(5, 97)]
    # Теоретическая кривая 1 / (1 - alpha) — число проб при неуспешном поиске в двойном хешировании (чёрная пунктирная линия).
    ax1.plot(xs, [1 / (1 - x) for x in xs], "k--", label="Теория 1/(1-α)")
    # Подписи осей и заголовок левого графика; yscale="log" — логарифмическая шкала по вертикали.
    ax1.set(xlabel="α", ylabel="Среднее число проб", title="Пробы в зависимости от α", yscale="log")
    # Правый график: столбики — для каждой длины цепочки показываем, сколько ячеек такую длину имеют.
    ax2.bar(list(lens), list(lens.values()))
    # Подписи осей и заголовок правого графика.
    ax2.set(xlabel="Длина цепочки", ylabel="Число ячеек", title="Распределение длин цепочек (α = 0,6)")
    # Включаем легенду на левом графике.
    ax1.legend()
    # Включаем полупрозрачную сетку на левом графике.
    ax1.grid(True, alpha=0.3)
    # Автоматически подгоняем расположение, чтобы подписи не накладывались друг на друга.
    plt.tight_layout()
    # Сохраняем графики в файл lab5_graphs.png (он нужен для отчёта).
    plt.savefig("lab5_graphs.png", dpi=150)
    # Показываем графики на экране.
    plt.show()


